//! Section layout — port of `build_map.py` / `pipeline.js` map building:
//! group by section, order sections along a 1-D PCA of their centroids, arrange
//! them on a grid, and lay each section's sounds out in a unit box by a local
//! 2-D projection. (First pass uses PCA-2D on the CLAP embeddings; the
//! similarity-preserving upgrade — UMAP/neighbor embedding — is M4 proper.)

use std::collections::{BTreeMap, HashMap};

/// World-space node radius (shared with the renderer for sizing + hit-testing).
pub const NODE_R: f32 = 1.6;

/// One analyzed sound, pre-layout.
pub struct Analyzed {
    pub path: String,
    pub filename: String,
    pub section: String,
    pub confidence: f32,
    pub embedding: Vec<f32>, // L2-normalized CLAP embedding
    pub envelope: Vec<f32>,  // peak-amplitude bars, drives the playback waveform
    pub duration: f32,       // seconds, for the waveform playhead
}

/// One laid-out node ready to render.
#[derive(Clone)]
pub struct Node {
    pub path: String,
    pub filename: String,
    pub section: String,
    pub confidence: f32,
    pub x: f32,
    pub y: f32,
    pub color: [f32; 3],
    pub rel_x: f32,
    pub rel_y: f32,
    pub section_id: u32,
    pub envelope: Vec<f32>,
    pub duration: f32,
    /// Spring target for the force sim. Equals the laid-out position until a
    /// drag re-anchors it (a valid drop makes where-you-dropped-it the new
    /// home; an invalid one leaves it alone so the node springs back).
    pub home_x: f32,
    pub home_y: f32,
    /// Force-sim velocity.
    pub vx: f32,
    pub vy: f32,
}

/// Stable small id per section name (used by the shader to test "same section
/// as hovered" for the highlight/dim/gradient effect). Public so the legend
/// (screen-space UI, computed outside this module) can drive the same highlight.
pub fn section_id(section: &str) -> u32 {
    use std::hash::{Hash, Hasher};
    let mut h = std::collections::hash_map::DefaultHasher::new();
    section.hash(&mut h);
    h.finish() as u32
}

pub struct SectionMeta {
    pub name: String,
    pub count: usize,
    pub color: [f32; 3],
    pub cx: f32,
    pub cy: f32,
}

